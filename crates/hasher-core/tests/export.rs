// ---------------------------------------------------------------------------- checksum

/// Righe non di commento e non vuote.
fn data_lines(text: &str, comment: char) -> Vec<&str> {
    text.lines()
        .filter(|l| !l.is_empty() && !l.starts_with(comment))
        .collect()
}

#[test]
fn checksum_gnu_format() {
    assert_eq!(ExportFormat::Checksum(Algo::Sha256).extension(), "sha256");
    let text = run_text(ExportFormat::Checksum(Algo::Sha256), &sample_results(), &options(false));
    assert!(!text.contains('\r'));

    let mut lines = text.lines();
    assert_eq!(
        lines.next().unwrap(),
        "# Hasher 1.2.3 \u{2014} Martini Multimedia s.a.s."
    );
    assert_eq!(lines.next().unwrap(), "# Generated on: 09/10/2026 12:30:15");

    let entries: Vec<(&str, &str)> = data_lines(&text, '#')
        .into_iter()
        .map(|l| l.split_once("  ").expect("two spaces"))
        .collect();
    assert_eq!(entries, vec![(SHA256_ABC, NAME_1), (SHA256_EMPTY, NAME_2)]);
    assert!(!text.contains(NA), "no skipped files expected for SHA-256");
}

#[test]
fn checksum_skips_files_without_the_algorithm() {
    let text = run_text(ExportFormat::Checksum(Algo::Md5), &sample_results(), &options(false));
    assert_eq!(data_lines(&text, '#').len(), 2);

    let mut results = sample_results();
    results[1].digests.remove(&Algo::Md5);
    let text = run_text(ExportFormat::Checksum(Algo::Md5), &results, &options(false));
    assert_eq!(data_lines(&text, '#'), vec![format!("{MD5_ABC}  {NAME_1}")]);
    assert!(text.lines().last().unwrap().starts_with('#'));
    assert!(text.contains("# MD5 N/A: 1"), "{text}");
}

#[test]
fn checksum_sfv_format_for_crc32() {
    let mut opts = options(false); // anche con hex minuscolo: SFV è sempre maiuscolo
    opts.uppercase_hex = false;
    assert_eq!(ExportFormat::Checksum(Algo::Crc32).extension(), "sfv");
    let text = run_text(ExportFormat::Checksum(Algo::Crc32), &sample_results(), &opts);

    let mut lines = text.lines();
    assert_eq!(
        lines.next().unwrap(),
        "; Hasher 1.2.3 \u{2014} Martini Multimedia s.a.s."
    );
    assert_eq!(lines.next().unwrap(), "; Generated on: 09/10/2026 12:30:15");
    assert!(!text.contains('#'));
    // Il secondo file non ha CRC32: saltato e contato in un commento.
    assert_eq!(
        data_lines(&text, ';'),
        vec![format!("{NAME_1} {}", CRC32_ABC.to_uppercase())]
    );
    assert!(text.lines().last().unwrap().starts_with(';'));
    assert!(text.contains("; CRC32 N/A: 1"), "{text}");
}

#[test]
fn checksum_files_roundtrip_through_the_parser() {
    let mut results = sample_results();
    results[1].info.name = "we\\ird\nname.bin".to_string(); // backslash e ritorno a capo
    let opts = options(false);

    let text = run_text(ExportFormat::Checksum(Algo::Sha256), &results, &opts);
    let entries = parse_text(&text, Some(Algo::Sha256));
    assert_eq!(entries.len(), 2, "{text}");
    assert_eq!(
        (entries[0].hex.as_str(), entries[0].file_name.as_str()),
        (SHA256_ABC, NAME_1)
    );
    assert_eq!(
        (entries[1].hex.as_str(), entries[1].file_name.as_str()),
        (SHA256_EMPTY, "we\\ird\nname.bin")
    );
    assert!(
        text.contains("\\\\ird\\nname.bin"),
        "name must be escaped GNU style: {text}"
    );

    let text = run_text(ExportFormat::Checksum(Algo::Crc32), &results, &opts);
    let entries = parse_text(&text, Some(Algo::Crc32));
    assert_eq!(entries.len(), 1, "{text}");
    assert_eq!(
        (entries[0].hex.as_str(), entries[0].file_name.as_str()),
        (CRC32_ABC, NAME_1)
    );
}

// --------------------------------------------------------------------------- uppercase

#[test]
fn uppercase_hex_affects_every_format() {
    let results = sample_results();
    let lower = options(false);
    let upper = options(true);

    // TXT
    let txt_l = run_text(ExportFormat::Txt, &results, &lower);
    let txt_u = run_text(ExportFormat::Txt, &results, &upper);
    assert!(txt_l.contains(SHA256_ABC) && !txt_l.contains(&SHA256_ABC.to_uppercase()));
    assert!(txt_u.contains(&SHA256_ABC.to_uppercase()) && !txt_u.contains(SHA256_ABC));

    // CSV
    let csv_u = run_text(ExportFormat::Csv, &results, &upper);
    assert!(csv_u.contains(&SHA256_ABC.to_uppercase()) && !csv_u.contains(SHA256_ABC));

    // JSON
    let json_u = run_text(ExportFormat::Json, &results, &upper);
    let v: serde_json::Value = serde_json::from_str(&json_u).unwrap();
    assert_eq!(v["files"][0]["hashes"]["sha256"], SHA256_ABC.to_uppercase());

    // Checksum GNU
    let sum_u = run_text(ExportFormat::Checksum(Algo::Sha256), &results, &upper);
    assert!(sum_u.contains(&format!("{}  {NAME_1}", SHA256_ABC.to_uppercase())));

    // SFV: maiuscolo in ogni caso.
    let sfv_l = run_text(ExportFormat::Checksum(Algo::Crc32), &results, &lower);
    let sfv_u = run_text(ExportFormat::Checksum(Algo::Crc32), &results, &upper);
    assert_eq!(data_lines(&sfv_l, ';'), data_lines(&sfv_u, ';'));
}

