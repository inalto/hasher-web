//! Test d'integrazione dell'esportazione: ogni formato viene prodotto in memoria e riletto.
//!
//! Portati dall'app desktop (`hasher/tests/export.rs`): `export::export(path, …)` è sostituito da
//! [`export_to_vec`], che restituisce i byte del documento (sul web offerti in download).

use chrono::{DateTime, Local, TimeZone};
use hasher_core::algo::Algo;
use hasher_core::checksum_file::parse_text;
use hasher_core::export::{export_to_vec, ExportFormat, ExportLabels, ExportOptions};
use hasher_core::fileinfo::{FileAttr, FileInfo};
use hasher_core::result::FileResult;
use std::collections::BTreeMap;
use std::path::PathBuf;
use std::time::Duration;

const CRC32_ABC: &str = "352441c2";
const MD5_ABC: &str = "900150983cd24fb0d6963f7d28e17f72";
const SHA256_ABC: &str = "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad";
const MD5_EMPTY: &str = "d41d8cd98f00b204e9800998ecf8427e";
const SHA256_EMPTY: &str = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855";

const NA: &str = "N/A";
const NAME_1: &str = "abc.txt";
const NAME_2: &str = "senza date \u{e9}\u{fc}.bin";

fn local(y: i32, mo: u32, d: u32, h: u32, mi: u32, s: u32) -> DateTime<Local> {
    Local.with_ymd_and_hms(y, mo, d, h, mi, s).unwrap()
}

fn digests(pairs: &[(Algo, &str)]) -> BTreeMap<Algo, Vec<u8>> {
    pairs.iter().map(|(a, h)| (*a, hex::decode(h).unwrap())).collect()
}

/// File 1: tutti i campi. File 2: nessuna data, nessun attributo, manca CRC32.
fn sample_results() -> Vec<FileResult> {
    let full = FileResult {
        id: 1,
        info: FileInfo {
            path: PathBuf::from("/data/docs/abc.txt"),
            name: NAME_1.to_string(),
            extension: Some("txt".to_string()),
            size: 1_234_567,
            created: Some(local(2026, 1, 2, 12, 4, 5)),
            modified: Some(local(2026, 3, 4, 12, 5, 6)),
            accessed: Some(local(2026, 5, 6, 12, 6, 7)),
            attributes: vec![FileAttr::ReadOnly, FileAttr::Hidden],
            unix_mode: Some(0o644),
            is_symlink: false,
        },
        digests: digests(&[
            (Algo::Crc32, CRC32_ABC),
            (Algo::Md5, MD5_ABC),
            (Algo::Sha256, SHA256_ABC),
        ]),
        elapsed: Duration::from_millis(12),
    };
    let sparse = FileResult {
        id: 2,
        info: FileInfo {
            path: PathBuf::from("/data/docs/sub/senza date \u{e9}\u{fc}.bin"),
            name: NAME_2.to_string(),
            extension: Some("bin".to_string()),
            size: 0,
            created: None,
            modified: None,
            accessed: None,
            attributes: vec![],
            unix_mode: None,
            is_symlink: false,
        },
        digests: digests(&[(Algo::Md5, MD5_EMPTY), (Algo::Sha256, SHA256_EMPTY)]),
        elapsed: Duration::ZERO,
    };
    vec![full, sparse]
}

fn labels() -> ExportLabels {
    ExportLabels {
        title: "Hash report".into(),
        generated_by: "Generated by".into(),
        generated_at: "Generated on".into(),
        file: "File".into(),
        path: "Path".into(),
        size: "Size".into(),
        size_bytes: "Size (bytes)".into(),
        created: "Created".into(),
        modified: "Modified".into(),
        attributes: "Attributes".into(),
        permissions: "Permissions".into(),
        algorithm: "Algorithm".into(),
        hash: "Hash".into(),
        files_count: "Files".into(),
        elapsed: "Elapsed".into(),
        not_available: NA.into(),
    }
}

fn options(uppercase: bool) -> ExportOptions {
    ExportOptions {
        algos: vec![Algo::Crc32, Algo::Md5, Algo::Sha256],
        uppercase_hex: uppercase,
        labels: labels(),
        app_name: "Hasher".into(),
        app_version: "1.2.3".into(),
        company: "Martini Multimedia s.a.s.".into(),
        generated_at: local(2026, 10, 9, 12, 30, 15),
        date_format: "%d/%m/%Y %H:%M:%S".into(),
    }
}

/// Esporta in memoria e restituisce i byte (mai vuoti).
fn run(format: ExportFormat, results: &[FileResult], opts: &ExportOptions) -> Vec<u8> {
    let bytes = export_to_vec(format, results, opts).unwrap_or_else(|e| panic!("{format:?}: {e:#}"));
    assert!(!bytes.is_empty(), "{format:?}: empty document");
    bytes
}

fn run_text(format: ExportFormat, results: &[FileResult], opts: &ExportOptions) -> String {
    String::from_utf8(run(format, results, opts)).expect("output must be UTF-8")
}

fn contains_bytes(haystack: &[u8], needle: &[u8]) -> bool {
    haystack.windows(needle.len()).any(|w| w == needle)
}

// ---------------------------------------------------------------------------------- TXT

#[test]
fn txt_report_content() {
    let txt = run_text(ExportFormat::Txt, &sample_results(), &options(false));
    assert!(!txt.contains('\r'), "TXT must use \\n line endings");
    assert!(txt.starts_with("Hash report\n===========\n"), "{txt}");
    assert!(txt.contains("Generated by: Hasher 1.2.3 \u{2014} Martini Multimedia s.a.s.\n"));
    assert!(txt.contains("Generated on: 09/10/2026 12:30:15\n"));
    assert!(txt.contains("Files: 2\n"));
    assert!(txt.contains(NAME_1));
    assert!(txt.contains(NAME_2));
    assert!(txt.contains("/data/docs/abc.txt"));
    assert!(txt.contains("1.23 MB"));
    assert!(txt.contains("1234567"));
    assert!(txt.contains("02/01/2026 12:04:05"));
    assert!(txt.contains("RH"));
    assert!(txt.contains("rw-r--r--"));
    // Algoritmi allineati al nome più lungo (SHA-256) e hash esatti.
    assert!(txt.contains(&format!("SHA-256: {SHA256_ABC}\n")), "{txt}");
    assert!(txt.contains(&format!("MD5    : {MD5_ABC}\n")));
    assert!(txt.contains(&format!("CRC32  : {CRC32_ABC}\n")));
    // Il secondo file non ha CRC32.
    assert!(txt.contains("CRC32  : N/A\n"));
    // Attributi e permessi: solo per il primo file.
    assert_eq!(txt.matches("Attributes").count(), 1);
    assert_eq!(txt.matches("Permissions").count(), 1);
    // Date assenti.
    assert!(txt.contains("Created     : N/A"));
    // Piè di pagina.
    assert!(txt
        .trim_end()
        .ends_with("Hasher 1.2.3 \u{2014} Martini Multimedia s.a.s."));
}

// ---------------------------------------------------------------------------------- CSV

#[test]
fn csv_has_bom_and_parses_back() {
    let bytes = run(ExportFormat::Csv, &sample_results(), &options(false));
    assert!(bytes.starts_with(b"\xEF\xBB\xBF"), "missing UTF-8 BOM");

    let mut rdr = csv::ReaderBuilder::new().delimiter(b',').from_reader(&bytes[3..]);
    let header: Vec<String> = rdr.headers().unwrap().iter().map(String::from).collect();
    assert_eq!(header.len(), 8 + 3);
    assert_eq!(
        header,
        [
            "File",
            "Path",
            "Size (bytes)",
            "Size",
            "Created",
            "Modified",
            "Attributes",
            "Permissions",
            "CRC32",
            "MD5",
            "SHA-256"
        ]
    );

    let rows: Vec<csv::StringRecord> = rdr.records().map(|r| r.unwrap()).collect();
    assert_eq!(rows.len(), 2);
    assert!(rows.iter().all(|r| r.len() == header.len()));

    let r0 = &rows[0];
    assert_eq!(&r0[0], NAME_1);
    assert_eq!(&r0[1], "/data/docs/abc.txt");
    assert_eq!(&r0[2], "1234567");
    assert_eq!(&r0[3], "1.23 MB");
    assert_eq!(&r0[4], "02/01/2026 12:04:05");
    assert_eq!(&r0[5], "04/03/2026 12:05:06");
    assert_eq!(&r0[6], "RH");
    assert_eq!(&r0[7], "rw-r--r--");
    assert_eq!(&r0[8], CRC32_ABC);
    assert_eq!(&r0[9], MD5_ABC);
    assert_eq!(&r0[10], SHA256_ABC);

    let r1 = &rows[1];
    assert_eq!(&r1[0], NAME_2);
    assert_eq!(&r1[2], "0");
    assert_eq!(&r1[4], NA);
    assert_eq!(&r1[6], "");
    assert_eq!(&r1[7], "");
    assert_eq!(&r1[8], NA, "missing algorithm must be not_available");
    assert_eq!(&r1[10], SHA256_EMPTY);
}

#[test]
fn csv_quotes_special_characters_and_defuses_formulas() {
    let mut results = sample_results();
    results[0].info.name = "a,\"b\".txt".to_string();
    results[1].info.name = "=HYPERLINK(\"http://x\")".to_string();
    let bytes = run(ExportFormat::Csv, &results, &options(false));
    let mut rdr = csv::Reader::from_reader(&bytes[3..]);
    let rows: Vec<csv::StringRecord> = rdr.records().map(|r| r.unwrap()).collect();
    assert_eq!(&rows[0][0], "a,\"b\".txt");
    assert_eq!(&rows[1][0], "'=HYPERLINK(\"http://x\")");
}

// --------------------------------------------------------------------------------- JSON

#[test]
fn json_parses_back() {
    let text = run_text(ExportFormat::Json, &sample_results(), &options(false));
    let v: serde_json::Value = serde_json::from_str(&text).unwrap();

    assert_eq!(v["app"]["name"], "Hasher");
    assert_eq!(v["app"]["version"], "1.2.3");
    assert_eq!(v["app"]["company"], "Martini Multimedia s.a.s.");
    let generated = DateTime::parse_from_rfc3339(v["generated_at"].as_str().unwrap()).unwrap();
    assert_eq!(generated.timestamp(), local(2026, 10, 9, 12, 30, 15).timestamp());

    let files = v["files"].as_array().unwrap();
    assert_eq!(files.len(), 2);

    let f0 = &files[0];
    assert_eq!(f0["name"], NAME_1);
    assert_eq!(f0["path"], "/data/docs/abc.txt");
    assert_eq!(f0["size"], 1_234_567);
    assert_eq!(f0["size_human"], "1.23 MB");
    assert_eq!(f0["hashes"]["sha256"], SHA256_ABC);
    assert_eq!(f0["hashes"]["md5"], MD5_ABC);
    assert_eq!(f0["hashes"]["crc32"], CRC32_ABC);
    assert_eq!(f0["attributes"], serde_json::json!(["read_only", "hidden"]));
    assert_eq!(f0["permissions"], "rw-r--r--");
    for key in ["created", "modified", "accessed"] {
        let s = f0[key].as_str().unwrap_or_else(|| panic!("{key} must be a string"));
        DateTime::parse_from_rfc3339(s).unwrap_or_else(|e| panic!("{key}: {e}"));
    }
    assert_eq!(
        DateTime::parse_from_rfc3339(f0["created"].as_str().unwrap())
            .unwrap()
            .timestamp(),
        local(2026, 1, 2, 12, 4, 5).timestamp()
    );

    let f1 = &files[1];
    assert_eq!(f1["name"], NAME_2);
    assert_eq!(f1["size"], 0);
    assert!(f1["created"].is_null());
    assert!(f1["modified"].is_null());
    assert!(f1["accessed"].is_null());
    assert!(f1["permissions"].is_null());
    assert_eq!(f1["attributes"], serde_json::json!([]));
    assert!(f1["hashes"]["crc32"].is_null(), "missing algorithm must be null");
    assert_eq!(f1["hashes"]["sha256"], SHA256_EMPTY);

    // L'ordine delle chiavi segue `opts.algos`.
    let (a, b, c) = (
        text.find("\"crc32\"").unwrap(),
        text.find("\"md5\"").unwrap(),
        text.find("\"sha256\"").unwrap(),
    );
    assert!(a < b && b < c, "hash keys out of order");
    assert!(text.contains("\n  \"app\""), "output must be pretty printed");
}

