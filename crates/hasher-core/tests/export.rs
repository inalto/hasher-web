/// Sostituisce `unwritable_destination_reports_the_path` del desktop (sul web non si scrive su
/// disco): un formato data non valido non manda in panic nessun formato, la data ricade su RFC 3339.
#[test]
fn invalid_date_format_falls_back_to_rfc3339() {
    let mut opts = options(false);
    opts.date_format = "%Q %d".into();
    for format in ExportFormat::BASIC
        .into_iter()
        .chain([ExportFormat::Checksum(Algo::Md5), ExportFormat::Checksum(Algo::Crc32)])
    {
        run(format, &sample_results(), &opts);
    }
    let txt = run_text(ExportFormat::Txt, &sample_results(), &opts);
    let rfc = local(2026, 10, 9, 12, 30, 15).to_rfc3339();
    assert!(txt.contains(&format!("Generated on: {rfc}\n")), "{txt}");
}

#[test]
fn mime_types_and_suggested_names() {
    let when = local(2026, 10, 9, 8, 7, 6);
    for format in ExportFormat::BASIC {
        assert_eq!(
            format.suggested_file_name(when),
            format!("hasher-20261009-080706.{}", format.extension())
        );
    }
    assert_eq!(
        ExportFormat::Checksum(Algo::Crc32).suggested_file_name(when),
        "hasher-20261009-080706.sfv"
    );
    assert!(ExportFormat::Txt.mime().starts_with("text/plain"));
    assert!(ExportFormat::Csv.mime().starts_with("text/csv"));
    assert_eq!(ExportFormat::Json.mime(), "application/json");
    assert!(ExportFormat::Xlsx.mime().contains("spreadsheetml"));
    assert!(ExportFormat::Docx.mime().contains("wordprocessingml"));
    assert!(ExportFormat::Checksum(Algo::Sha256).mime().starts_with("text/plain"));
}
